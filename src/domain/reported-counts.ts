/**
 * Числа, які назвали САМІ джерела — і жодного числа, якого вони не називали.
 *
 * ================================================================================================
 * Межа, заради якої цей модуль існує окремо
 * ================================================================================================
 *
 * `CONTEXT.md` і `src/services/attack-analytics.ts` тримають правило, яке в цьому проєкті коштувало
 * найдорожче: рахувати можна ПОВІДОМЛЕННЯ, а не засоби. Публічна сторінка атак каже «повідомлень»
 * там, де хочеться сказати «цілей», бо канал пише «шахеди на Полтавщині» й не пише, скільки їх.
 *
 * Розбір атаки після відбою (рішення власника 20.08.2026) просить «приблизний підрахунок цілей».
 * Єдиний спосіб дати його, не вигадуючи військової статистики з телеграм-постів, — це процитувати
 * число, яке написало саме джерело: «10 шахедів курсом на Київщину» — це твердження каналу, і
 * переказати його можна, бо переказ лишається твердженням каналу. Тому:
 *
 *  * витягуються ЛИШЕ числа, що стоять при слові з переліку нижче («шахедів», «цілей», «ракет»);
 *  * числа з різних повідомлень НІКОЛИ не додаються. Дві групи по пʼять, про які написали два
 *    канали, — це, найімовірніше, одна група, описана двічі, і сума перетворила б переказ на власну
 *    оцінку. Береться максимум, названий в одному повідомленні, і він так і підписується;
 *  * усе, що не число при відомому слові, не повертається взагалі. Мовчання тут означає «джерела
 *    кількості не називали», і це чесна й найчастіша відповідь.
 *
 * Чистий модуль: ні бази, ні моделі, ні конфігурації. Усе, що він знає, — це рядок тексту.
 */

import type { ThreatType } from '../types.js';

/**
 * Слово, при якому число означає кількість цілей, і клас, до якого воно належить.
 *
 * Лише основи слів: канали пишуть у всіх відмінках («5 шахедів», «5 шахеда», «групу з 5 шахедів»),
 * і перелічувати форми означало б програвати першому ж новому написанню. Широта основи тут безпечна
 * не сама по собі, а тому, що слово рахується лише разом із числом поруч: «ракетна небезпека» не
 * дає нічого, бо числа при ній немає, а «2 ракети» дає, бо воно є. Саме число, а не слово, є тим,
 * що вирішує, чи джерело назвало кількість.
 *
 * Мітка називає КЛАС, під яким число показують, а не конкретний виріб: «гербера» й «мопед» їдуть
 * під «ударні БпЛА» з тієї самої причини, з якої там уже їде «дрон» — інакше один розбір мав би два
 * рядки про той самий клас, і показаний був би той, чиє число більше. Це не твердження про те, що
 * саме летіло: летіло те, що назвало джерело, а число лишається його числом.
 *
 * Телеграфні форми, яких тут бракувало й через які число, назване каналом, мовчки зникало з
 * розбору:
 *
 *  * «3х реакт» — реактивні БпЛА. Форму «3х» уже читає {@link BEFORE}; бракувало самого слова.
 *    Основа обрізана до «реакт|реактив», щоб «реактор» (а це вже про ЗАЕС, не про ціль) не став
 *    трьома БпЛА;
 *  * «гербера», «мопед» — як канали називають БпЛА, коли не пишуть «шахед»;
 *  * «шахід» — друге написання того самого слова, яке основа «шахед» не накривала;
 *  * парадигма КАБів: «4 КАБи» читалося, а «2 КАБів», «КАБами» й «6 ФАБ-500» — ні, бо після основи
 *    дозволялася рівно одна літера. Закінчення перелічені, а не відкриті, бо «каб» — початок і
 *    «кабеля», і «кабіни», і «фабрики», а число поруч із ними буває.
 */
const COUNTED_WORDS: ReadonlyArray<{ pattern: RegExp; threatType: ThreatType; label: string }> = [
  {
    pattern: /^(?:шах[еі]д|герань|гербер|geran|бпла|дрон|безпілотник|мопед|реакт(?:ив|$))/iu,
    threatType: 'uav', label: 'ударні БпЛА'
  },
  { pattern: /^(?:балісти|іскандер|кинджал|kn-23|кн-23)/iu, threatType: 'ballistic_missile', label: 'балістика' },
  { pattern: /^(?:калібр|крилат|х-101|х-555|х-59|х-31)/iu, threatType: 'cruise_missile', label: 'крилаті ракети' },
  // Кінцевий дефіс — це хвіст від «ФАБ-500»: {@link BEFORE} бере слово разом із ним, бо цифри
  // моделі вже за межею слова.
  { pattern: /^(?:каб|фаб)(?:ами|ах|ам|ів|и|і|у|а|ы)?-?$/iu, threatType: 'guided_air_bomb', label: 'КАБи' },
  // Найзагальніше — останнім: «цілей» і «ракет» без уточнення класу означають рівно те, що написано.
  { pattern: /^ракет/iu, threatType: 'cruise_missile', label: 'ракети' },
  { pattern: /^(?:ціл[ьіеяю]|об'єкт|обʼєкт)/iu, threatType: 'unknown', label: 'цілі' }
];

/**
 * Число перед словом («10 шахедів») або після нього («шахедів — 10», «БпЛА: 4»).
 *
 * Верхня межа в дві цифри плюс третя — навмисна: чотиризначне число при слові «цілей» у пості
 * моніторингового каналу майже завжди є роком, номером посту або чужою статистикою за місяць, і
 * пропустити його дешевше, ніж написати читачеві «джерела називали 2026 цілей».
 *
 * У {@link AFTER} дефіс як роздільник вимагає пробілу ПЕРЕД собою, а тире й двокрапка — ні. Без
 * цього «ФАБ-500» читалося як «ФАБ — 500», тобто індекс виробу ставав кількістю: до трьох цифр
 * «ФАБ-250» проходило б і через межу в 300. Роздільник без пробілу — це позначення моделі
 * («Х-101», «ФАБ-250», «KN-23»), а не «слово — число», і жодне джерело так кількості не пише.
 */
const BEFORE = /(\d{1,3})\s*(?:[×xх]\s*)?([\p{L}''-]+)/gu;
const AFTER = /([\p{L}''-]+)\s*(?:[—:]|\s-)\s*(\d{1,3})\b/gu;

export interface ReportedCount {
  count: number;
  threatType: ThreatType;
  label: string;
}

function classify(word: string): { threatType: ThreatType; label: string } | null {
  for (const entry of COUNTED_WORDS) {
    if (entry.pattern.test(word)) return { threatType: entry.threatType, label: entry.label };
  }
  return null;
}

/** Усі кількості, названі в ОДНОМУ повідомленні. Порожній масив — джерело кількості не називало. */
export function reportedCounts(text: string): ReportedCount[] {
  const found: ReportedCount[] = [];
  const push = (raw: string, word: string) => {
    const count = Number(raw);
    if (!Number.isFinite(count) || count <= 0 || count > 300) return;
    const matched = classify(word);
    if (matched) found.push({ count, ...matched });
  };
  for (const match of text.matchAll(BEFORE)) push(match[1]!, match[2]!);
  for (const match of text.matchAll(AFTER)) push(match[2]!, match[1]!);
  return found;
}

/**
 * Найбільше, що назвало ОДНЕ повідомлення, по кожному класу.
 *
 * Не сума й ніколи не буде сумою — див. шапку модуля. Ключем є клас, а не мітка, щоб «10 шахедів» з
 * одного каналу й «10 БпЛА» з другого не стали двома різними рядками про те саме.
 */
export function peakReportedCounts(texts: readonly string[]): ReportedCount[] {
  const peaks = new Map<ThreatType, ReportedCount>();
  for (const text of texts) {
    for (const reported of reportedCounts(text)) {
      const current = peaks.get(reported.threatType);
      if (!current || reported.count > current.count) peaks.set(reported.threatType, reported);
    }
  }
  return [...peaks.values()].sort((left, right) => right.count - left.count);
}
