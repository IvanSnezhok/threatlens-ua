/**
 * Зони, з яких джерела повідомляють про походження загрози.
 *
 * Каталог `locations` тримає виключно українські адмінодиниці — 55 точок із координатами, усі в
 * межах держави, — і це правильно: він описує те, ЩО захищають, а не те, звідки б'ють. Але джерела
 * регулярно називають походження («пуски крилатих ракет з акваторії Чорного моря»),
 * і досі ця частина повідомлення зникала безслідно: морський індикатор піднімав подію до
 * `nationalScope`, а `FOREIGN_PLACE_STEMS` гасив іноземну назву, щоб вона не резолвилася в українське
 * місто. Обидва механізми правильні й лишаються; ця таблиця додає третій шлях — назвати зону, не
 * називаючи місця.
 *
 * ЩО ТУТ Є І ЧОГО ТУТ НЕМАЄ. Тут немає аеродромів, портів, позицій і взагалі жодного об'єкта:
 * `CONTEXT.md` забороняє показувати точні військові координати, і заборона діє незалежно від того,
 * чи назвало об'єкт джерело. Зона — це область розміром у сотні кілометрів, координата якої означає
 * «десь тут», а не «ось тут». Різниця та сама, що між «з акваторії Чорного моря» і координатами
 * корабля.
 *
 * ЧОМУ ЗОНА БЕРЕТЬСЯ З ТЕКСТУ, А НЕ З ТИПУ ІНДИКАТОРА. Спокуса зіставити «зліт стратегічної авіації»
 * із північним сходом велика й хибна: повідомлення про зліт не називає аеродрому, і зона, виведена з
 * самого лише класу зброї, була б нашим припущенням у вигляді карти. Правило продукту читається
 * дослівно — «напрямки на карті відображаються лише тоді, коли їх повідомило джерело», — тож зона
 * зчитується з тих самих слів, які написав публікатор, і жодного разу не добудовується.
 *
 * ЧОМУ ТУТ ЛИШЕ АКВАТОРІЇ, І ЖОДНОГО РУМБА. Перший варіант каталогу мав ще «північний» і «східний»
 * напрямки за патернами «з півночі», «зі сходу». Перевірка на реальному трафіку показала, що це
 * зовсім інша заява: за сім днів такі формулювання трапилися 96 разів, і майже всі мали вигляд
 * «БпЛА курсом на Київ з півночі» або «Київщина: 6 на Бровари зі сходу». Румб там означає бік, з
 * якого цілі ЗАХОДЯТЬ НА КОНКРЕТНЕ УКРАЇНСЬКЕ МІСТО, а не зону старту за кордоном — і іконка на
 * широті 52.9° стверджувала б місце, про яке ніхто не говорив. Цей бік підльоту вже описує
 * `directionText`, і дублювати його зоною означало б перетворити відносний напрямок на географію.
 *
 * Акваторії такої двозначності не мають: «з акваторії Чорного моря» не буває відносним ні до чого.
 * Тому зона лишається рівно там, де формулювання джерела саме по собі називає місце пуску.
 */

import type { OriginZoneId } from '../types.js';

export type { OriginZoneId };

export interface OriginZone {
  id: OriginZoneId;
  /** Як зона зветься для читача — тим самим словом, яким її називають джерела. */
  name: string;
  /**
   * Приблизний центр зони, [довгота, широта].
   *
   * Навмисно грубий і навмисно не в Україні. Це якір для іконки, а не позиція чогось: зсунути його
   * на пів градуса не змінює жодного твердження, бо твердження — «звідти», а не «звідси».
   */
  anchor: [number, number];
  /**
   * Слова, якими джерела називають цю зону.
   *
   * Патерни навмисно вимагають прийменника походження («з», «із», «зі», «в акваторії»), а не самої
   * лише назви: «збито над Чорним морем» — це місце ураження, а не походження, і воно не має
   * запалювати зону пуску.
   */
  patterns: RegExp[];
}

export const ORIGIN_ZONES: readonly OriginZone[] = [
  {
    id: 'black_sea',
    name: 'акваторія Чорного моря',
    anchor: [32.2, 43.3],
    patterns: [
      /(?:з|із|зі)\s+акваторі[іїя]\s+чорного\s+мор/iu,
      /в\s+акваторі[іїя]\s+чорного\s+мор/iu,
      /(?:з|із|зі)\s+чорного\s+мор/iu,
      /чорноморськ\w*\s+акваторі/iu
    ]
  },
  {
    id: 'azov_sea',
    name: 'акваторія Азовського моря',
    anchor: [36.9, 46.1],
    patterns: [
      /(?:з|із|зі)\s+акваторі[іїя]\s+азовського\s+мор/iu,
      /в\s+акваторі[іїя]\s+азовського\s+мор/iu,
      /(?:з|із|зі)\s+азовського\s+мор/iu
    ]
  }
];

const BY_ID = new Map<string, OriginZone>(ORIGIN_ZONES.map((zone) => [zone.id, zone]));

export function originZoneById(id: string | null | undefined): OriginZone | null {
  return id ? BY_ID.get(id) ?? null : null;
}

/**
 * Зона походження, названа в тексті, або `null`.
 *
 * Перша, що збіглася. Порядок таблиці значення не має, доки зони не перетинаються: два моря названі
 * різними словами, і жодне повідомлення не може вказувати на обидва.
 *
 * Повертається САМЕ ЗОНА, не координата: викликач вирішує, чи має він право її показати. Класифікація
 * лише фіксує, що джерело її назвало.
 */
export function detectOriginZone(text: string): OriginZone | null {
  if (!text) return null;
  for (const zone of ORIGIN_ZONES) {
    for (const pattern of zone.patterns) {
      if (pattern.test(text)) return zone;
    }
  }
  return null;
}
