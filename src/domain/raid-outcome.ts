/**
 * Що джерела повідомляли про наслідки — вибухи, роботу ППО, збиття — і як про це говорити.
 *
 * ================================================================================================
 * Чому це маркери, а не висновки
 * ================================================================================================
 *
 * Розбір атаки після відбою має сказати про «можливе місце влучання чи збиття» (рішення власника
 * 20.08.2026). Ми цього не знаємо і знати не можемо: у нас є пости каналів, а не дані обʼєктового
 * контролю. Що ми справді маємо — це те, що хтось написав слово «вибухи» о 02:41, назвавши район.
 *
 * Тому модуль не робить висновку, а класифікує ЛЕКСИКУ: повідомлення несе маркер «вибух», «робота
 * ППО» чи «збито» — чи не несе жодного. Далі розбір каже рівно те, що з цього випливає: «канали
 * повідомляли про вибухи», а не «було влучання». Різниця між цими двома реченнями — це і є вся
 * різниця між переказом і вигадкою, і вона тримається тим, що висновку тут просто немає де
 * зʼявитися: функція повертає слова, а не оцінку.
 *
 * `збито` і `вибухи` навмисно окремі маркери, хоч у пості вони часто стоять поруч. Читач, який
 * зранку дивиться, що було над його районом, розрізняє «чули вибух» і «збили» — і система, яка
 * зливає їх у «наслідки», відповідає не на те питання, яке їй поставили.
 *
 * Чистий модуль: жодної бази, жодної моделі.
 */

export const RAID_OUTCOMES = ['explosion', 'air_defence', 'downed', 'debris'] as const;
export type RaidOutcome = (typeof RAID_OUTCOMES)[number];

// `\w` тут не вживається НІДЕ, і це не стиль. У JavaScript `\w` — це [A-Za-z0-9_] навіть із прапорцем
// `u`, тож «робота» не є `робот\w+`: жодна кирилична літера в `\w` не входить. Той самий підводний
// камінь має `\b`, який визначено через `\w` і який усередині суцільно кириличного слова не існує
// взагалі. Тому основи слів тут — це префікси, а не «основа плюс закінчення».

const MARKERS: ReadonlyArray<{ outcome: RaidOutcome; pattern: RegExp }> = [
  // «вибух», «вибухи», «прильот», «влучання». `детонац` — те саме слово в лексиконі частини каналів.
  { outcome: 'explosion', pattern: /вибух|детонац|приліт|прильот|влучан/iu },
  // «працює ППО», «робота ППО», «відпрацювала ППО» — дієслово й абревіатура в межах одного речення.
  {
    outcome: 'air_defence',
    pattern: /(?:робот|працю|відпрац)[\p{L}]*[^.!?\n]{0,30}(?:ппо|пво)|(?:ппо|пво)[^.!?\n]{0,30}(?:працю|робот)/iu
  },
  { outcome: 'downed', pattern: /збит|знищен|подавлен|ліквідован/iu },
  { outcome: 'debris', pattern: /уламк/iu }
];

/** Маркери, які несе один текст. Порожній масив — джерело про наслідки не писало. */
export function raidOutcomes(text: string): RaidOutcome[] {
  return MARKERS.filter((marker) => marker.pattern.test(text)).map((marker) => marker.outcome);
}

/**
 * Як назвати маркер у тексті для читача — у минулому часі й від імені джерел, не від нашого.
 *
 * Формулювання належить цьому модулю, а не форматувальнику бота: рівно тут відомо, що саме було
 * знайдено — слово в чужому пості, — і рівно тут це можна сказати так, щоб переказ не перетворився
 * на власне твердження. Форматувальник, який писав би «влучання в Дарницькому районі», зробив би з
 * маркера факт, якого ніхто не встановлював.
 */
export const RAID_OUTCOME_PHRASES: Record<RaidOutcome, string> = {
  explosion: 'повідомляли про вибухи',
  air_defence: 'повідомляли про роботу ППО',
  downed: 'повідомляли про збиття',
  debris: 'повідомляли про падіння уламків'
};

export function raidOutcomePhrase(outcome: RaidOutcome): string {
  return RAID_OUTCOME_PHRASES[outcome];
}
