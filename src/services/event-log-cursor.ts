/**
 * Скільки читач `system_event_log` має права взяти за один прохід.
 *
 * `version` — це `bigserial`, і значення видається на INSERT, а рядок стає видимим на COMMIT. Між
 * цими двома моментами може минути скільки завгодно часу, тож порядок версій і порядок появи рядків
 * не збігаються. `persistOfficialAlertSnapshot` тримає одну транзакцію на весь знімок і пише
 * `alert.started` усередині циклу по областях — тобто бере НИЗЬКУ версію рано й комітить пізно, поки
 * коротка транзакція інжесту встигає взяти ВИЩУ версію й закомітити першою.
 *
 * Читач з курсором «version > $1» бачив у цей момент лише вищу версію, віддавав її та посував
 * курсор — і нижча версія, з'явившись, лишалася НАЗАВЖДИ під курсором. Для розсилки, чий курсор
 * довговічний (`worker_state`), це означало непроведене сповіщення про початок тривоги, і тим
 * імовірніше, чим довша транзакція знімка, тобто саме під час загальнонаціональної тривоги.
 *
 * Правило нижче знімає це припущення: читач бере лише БЕЗПЕРЕРВНИЙ відрізок версій і зупиняється
 * перед першим розривом. Розрив означає одне з двох — або транзакція з тією версією ще не
 * закомічена (тоді чекати правильно, вона от-от з'явиться), або її відкотили й значення
 * послідовності згоріло (тоді чекати марно). Розрізнити їх у момент читання неможливо, тому розрив
 * тримає відрізок лише поки він свіжий.
 */

/** Мінімум, який читач має вміти прочитати з рядка журналу, щоб застосувати правило. */
export interface EventLogRow {
  version: number | string;
  created_at: Date;
}

/**
 * Скільки розрив стримує видачу, перш ніж вважатися вічним.
 *
 * Верхня межа тут — тривалість найдовшої транзакції запису. `persistOfficialAlertSnapshot` під час
 * загальнонаціональної тривоги робить сотні звернень без простою й перевалює за п'ятнадцять секунд
 * (див. коментар у `src/db/pool.ts`), тож хвилина дає чотирикратний запас. Занизьке значення
 * повертає саме ту втрату, заради якої все це написано; зависоке лише відкладає видачу після
 * відкоту, який трапляється рідко й нічого не втрачає.
 */
export const EVENT_LOG_GAP_GRACE_MS = 60_000;

/**
 * Префікс рядків, який можна віддати, не ризикуючи перестрибнути ще невидиму нижчу версію.
 *
 * `rows` мають бути відсортовані за `version` і всі бути вищими за `cursor` — тобто рівно те, що
 * повертає запит читача. Повертається новий масив, вхідний не змінюється.
 */
export function deliverableRun<T extends EventLogRow>(rows: readonly T[], cursor: number, now: number): T[] {
  const run: T[] = [];
  let expected = cursor + 1;
  for (const row of rows) {
    const version = Number(row.version);
    if (version !== expected && now - row.created_at.getTime() < EVENT_LOG_GAP_GRACE_MS) break;
    run.push(row);
    expected = version + 1;
  }
  return run;
}
