-- ================================================================================================
-- 054 — рівень тривоги: колір як ПРИКМЕТА вже оголошеної тривоги
-- ================================================================================================
--
-- Уряд запровадив диференційоване оповіщення; чинне з 06:00 06.09.2026. Оголошена тривога тепер
-- може нести колір: жовтий («дронова небезпека») або червоний («масована дронова», «ракетна» чи
-- «ракетно-дронова загроза»). Зміна кольору всередині тієї самої тривоги — це ЗАМІНА сказаного
-- раніше, а не нова тривога й не відбій.
--
-- Живий зріз фіда `?source=klimenko&raw` (22.09.2026 19:06 за Києвом), з якого ця міграція й
-- писалася: 153 вузли, поле `alert_level` є на КОЖНОМУ; 34 ввімкнених, з них 12 `red` (Луганщина
-- цілою, 8 районів Донеччини, 3 райони Дніпропетровщини), 20 `yellow` і 2 без кольору (АР Крим і
-- Севастополь — постійні записи з 2022 року). Тобто `null` — не виняток і не збій, а нормальний,
-- найчастіший стан: 119 зі 153 вузлів не мають кольору взагалі.
--
-- ------------------------------------------------------------------------------------------------
-- Чому це НОВІ стовпці, а не нові значення `alert_type`
-- ------------------------------------------------------------------------------------------------
--
-- `alert_type` — це ТОТОЖНІСТЬ періоду: `alert_periods` унікальний по
-- (location_id, alert_type, started_at), `reconcileAggregateAlert` шукає активний період саме по
-- парі (location_id, alert_type), і знімок зводиться окремо для кожного типу. Записати
-- диференційований різновид туди означало б, що перехід жовтий→червоний — це інша пара, отже інший
-- період: система відкрила б другий період і ЗАКРИЛА перший, а закриття періоду — це «⚪ Відбій
-- тривоги» в боті й зелена область на карті посеред тривоги, яка щойно ПОСИЛИЛАСЯ. Це найгірша
-- з доступних тут відмов, і саме її ці стовпці існують, щоб зробити неможливою.
--
-- Тому `alert_type` лишається `air_raid` і значить рівно те, що значив.
--
-- ------------------------------------------------------------------------------------------------
-- Чого ці стовпці НЕ роблять — ніколи, за жодних обставин
-- ------------------------------------------------------------------------------------------------
--
--   * не є тотожністю періоду: у жодному UNIQUE, PRIMARY KEY чи ON CONFLICT їх немає і не буде;
--   * не беруть участі в рішенні «тривога є чи немає». Це рішення — і далі `bool_or(counts AND
--     holds)` по рядках джерел, із тим самим пріоритетом API, тією самою перевіркою живості й тим
--     самим `ALERT_END_DEBOUNCE_SECONDS`. Рівень рахується ПОРУЧ із цією диз'юнкцією, з тих самих
--     рядків, що вже тримають тривогу, і не може зробити `holds`, `counts` чи `would_hold` хибними;
--   * не відкривають і не закривають періодів: зміна рівня — це UPDATE наявного рядка;
--   * `null` не означає «менша небезпека» — лише «джерело кольору не назвало».
--
-- ------------------------------------------------------------------------------------------------
-- Індекси: жодного на самі стовпці рівня, і рівно один на запит, який зміна рівня породжує
-- ------------------------------------------------------------------------------------------------
--
-- На `alert_level`/`alert_kind` індексу НЕМАЄ, бо за ними не фільтрує ніхто: зведення вже читає всі
-- рядки пари (location_id, alert_type) через `alert_source_states_pair_idx` (міграція 053) і бере
-- колір із тих самих рядків; `activeAlerts()` вже відбирає періоди по `status='active'` через
-- `alert_periods_active_idx` і лише ДОдає колір у вибірку; бот читає період по id. Жодного
-- `WHERE alert_level = …` в `src/` немає, а індекс без запиту за ним — це не нуль, а запис на
-- кожен INSERT у таблицю, яку пишуть п'ятнадцять разів на хвилину на кожне джерело.
--
-- Один запит нова подія все-таки породжує, і він приходить у цій самій міграції — за правилом
-- міграції 053: індекс з'являється разом із запитом, який його читає, або не з'являється зовсім.
-- Розсилка мусить відповісти «що цьому чатові казали про цю тривогу востаннє», перш ніж надіслати
-- зміну рівня: чат, якому про тривогу не казали, зміни кольору не отримує, і повтор тієї самої
-- пари теж. Відповідь читається з `notification_outbox` як
-- `DISTINCT ON (chat_id) … WHERE alert_period_id=$1 ORDER BY chat_id, created_at DESC`.
--
-- Виміряно на бойовій базі 22.09.2026: у `notification_outbox` 10 248 рядків / 15 МБ, з них 2 528 з
-- `alert_period_id`; індексів п'ять — `notification_outbox_pkey`,
-- `notification_outbox_idempotency_key_key`, `outbox_pending_idx`, `outbox_sending_stale_idx`,
-- `outbox_governor_pending_idx` — і жоден із них не починається з `alert_period_id`. Тобто
-- зовнішній ключ на `alert_periods` не індексований узагалі, і цей запит був би послідовним
-- сканом усієї таблиці на КОЖНУ зміну рівня, у транзакції розсилки. Ретенції в таблиці немає, тож
-- скан дорожчає рівно настільки, скільки система пропрацювала.
--
-- Частковий по `notification_type`, бо решта рядків на це питання не відповідає: чатові казали про
-- тривогу рівно тими двома типами. `created_at DESC` третім стовпцем — щоб `DISTINCT ON` брав
-- перший рядок групи з індексу, а не сортував групу.
--
-- Звідси й преамбула: `src/db/pool.ts` шле `statement_timeout = 15s` стартовим параметром, отже він
-- в'яже й DDL, а `src/index.ts` чекає `migrate()` ДО `buildServer()` — міграція, яка впала по
-- таймауту, це не повільний деплой, а контейнер, який ніколи не дійде до listen(). Побудова індексу
-- над таблицею без ретенції — саме той випадок, тривалість якого росте з віком інсталяції.
-- `lock_timeout` — обов'язковий супутник зняття: `CREATE INDEX` бере SHARE, і швидко впасти на
-- блокуванні строго краще, ніж повісити старт. Це аргумент міграцій 036 і 053, застосований ще раз.
--
-- Самі `ADD COLUMN` преамбули не потребують: nullable-стовпець без DEFAULT не переписує таблиці й
-- тримає ACCESS EXCLUSIVE рівно на час оновлення каталогу.
SET LOCAL statement_timeout = 0;
SET LOCAL lock_timeout = '10s';

-- ------------------------------------------------------------------------------------------------
-- 1. Що сказало ОДНЕ джерело
-- ------------------------------------------------------------------------------------------------
--
-- Рівень зберігається на рядку джерела, а не лише на періоді, бо джерела розходяться: у тому самому
-- зрізі один фід каже про район `red`, інший про ту саму область не каже нічого. Без цих стовпців
-- правило «береться найсильніший із тих, хто ТРИМАЄ тривогу» не мало б із чого рахуватися.
ALTER TABLE alert_source_states
  ADD COLUMN IF NOT EXISTS alert_level text
    CHECK (alert_level IS NULL OR alert_level IN ('yellow','red')),
  ADD COLUMN IF NOT EXISTS alert_kind text
    CHECK (alert_kind IS NULL OR alert_kind IN ('drones','missiles','drones_missiles'));

COMMENT ON COLUMN alert_source_states.alert_level IS
  'Колір, який САМЕ ЦЕ джерело назвало для цієї тривоги: yellow | red, або NULL — «кольору не назвало» (нормальний і найчастіший стан). НІКОЛИ не є тотожністю рядка і НІКОЛИ не бере участі в рішенні «тривога є чи немає»: рішення лишається bool_or по active/missing_since із пріоритетом API, перевіркою живості й дебаунсом відбою, і цей стовпець не може зробити жодного з них хибним.';

COMMENT ON COLUMN alert_source_states.alert_kind IS
  'Чим загрожує, за словами САМЕ ЦЬОГО джерела: drones | missiles | drones_missiles, або NULL — не назвало. Вісь, незалежна від alert_level. НІКОЛИ не є тотожністю рядка, НІКОЛИ не бере участі в рішенні «тривога є чи немає» і НІКОЛИ не пишеться в alert_type — alert_type лишається air_raid, інакше зміна різновиду відкрила б другий період і закрила перший.';

-- ------------------------------------------------------------------------------------------------
-- 2. Що з цього вийшло у зведенні
-- ------------------------------------------------------------------------------------------------
--
-- Найсильніший колір серед рядків, що ТРИМАЮТЬ тривогу (red > yellow > немає), і різновид того
-- рядка. Обережність тут дорожча за консенсус: якщо одне джерело каже `red`, а друге `yellow`,
-- період червоний. Якщо на найсильнішому рівні джерела називають РІЗНІ різновиди — `alert_kind`
-- лишається NULL: вигадувати різновид, якого ніхто не оголошував, ця система не має права.
ALTER TABLE alert_periods
  ADD COLUMN IF NOT EXISTS alert_level text
    CHECK (alert_level IS NULL OR alert_level IN ('yellow','red')),
  ADD COLUMN IF NOT EXISTS alert_kind text
    CHECK (alert_kind IS NULL OR alert_kind IN ('drones','missiles','drones_missiles')),
  ADD COLUMN IF NOT EXISTS alert_level_changed_at timestamptz;

COMMENT ON COLUMN alert_periods.alert_level IS
  'Найсильніший колір серед джерел, що тримають цю тривогу (red > yellow), або NULL — кольору не назвав ніхто. Прикмета періоду, а не його тотожність: не входить у UNIQUE (location_id, alert_type, started_at), не відкриває й не закриває періоду, і НІКОЛИ не бере участі в рішенні «тривога є чи немає». Зниження red → yellow не є відбоєм і ніколи ним не підписується.';

COMMENT ON COLUMN alert_periods.alert_kind IS
  'Різновид загрози на найсильнішому рівні: drones | missiles | drones_missiles, або NULL — не назвали або джерела на цьому рівні розійшлися. Прикмета, не тотожність; у alert_type не потрапляє ніколи.';

COMMENT ON COLUMN alert_periods.alert_level_changed_at IS
  'Коли колір або різновид цього періоду востаннє ЗАМІНИЛИ на інший. NULL — не змінювали жодного разу (у тому числі на щойно відкритому періоді: перший колір — це не зміна). Ніколи не зсуває started_at і ніколи не є ознакою нового періоду: тривога та сама, відбою не було.';

COMMENT ON TABLE alert_periods IS
  'Зведений період офіційної тривоги для пари (location_id, alert_type). alert_type лишається типом тривоги (air_raid, artillery, …) і НЕ несе диференційованого рівня: колір живе в alert_level/alert_kind саме для того, щоб зміна кольору була UPDATE цього рядка, а не новим періодом із відбоєм попереднього.';

-- ------------------------------------------------------------------------------------------------
-- 3. «Що цьому чатові казали про цю тривогу востаннє»
-- ------------------------------------------------------------------------------------------------
--
-- Індекс під запит розсилки, описаний у преамбулі. Він же дає зовнішньому ключу
-- `notification_outbox.alert_period_id` перший індекс узагалі — досі кожне видалення чи зміна
-- періоду перевіряли його послідовним сканом.
--
-- Зміна рівня — єдина подія, яка мусить знати, ЩО читачеві вже сказали: відбій і початок тривоги
-- самодостатні, а «тепер червоний» без «була тривога» — це повідомлення нізвідки. Тому запит
-- існує лише на цьому шляху, і індекс приходить разом із ним.
CREATE INDEX IF NOT EXISTS outbox_alert_period_told_idx
  ON notification_outbox (alert_period_id, chat_id, created_at DESC)
  WHERE notification_type IN ('alert_start','alert_level_change');

COMMENT ON INDEX outbox_alert_period_told_idx IS
  'Відповідає на «що цьому чатові казали про цей період востаннє» — DISTINCT ON (chat_id) WHERE alert_period_id=$1 ORDER BY chat_id, created_at DESC. Частковий: на це питання відповідають лише рядки alert_start і alert_level_change.';
