-- Зона походження, названа джерелом.
--
-- Досі ця частина повідомлення зникала без сліду. «Пуски крилатих ракет з акваторії Чорного моря»
-- давало nationalScope і жодної географії, бо каталог `locations` тримає виключно українські
-- адмінодиниці — 55 точок із координатами, усі в межах держави. Це правильно й лишається: каталог
-- описує те, ЩО захищають. Але звідки б'ють, джерела називають регулярно, і карта досі не могла
-- цього повторити.
--
-- Колонка, а не таблиця й не рядок у `locations`. Причина в тому, чого ми НЕ хочемо зачепити:
-- рядок у `locations` одразу потрапив би в підписки, у територіальні стани, у дерево предків і в
-- добову синхронізацію KATOTTG, яка тієї зони не знає й не має знати. Зона — це властивість
-- ОДНІЄЇ класифікації, а не місце в адміністративному устрої країни, і зберігати її треба там, де
-- живе решта того, що вичитали з тексту: поруч із direction_text.
--
-- Значення — стабільні ідентифікатори з src/domain/origin-zones.ts. Координати навмисно НЕ тут:
-- вони не дані, а спосіб намалювати зону, і живуть у коді разом із патернами розпізнавання.
-- CHECK свідомо відсутній: перелік зон змінюється разом із патернами, тобто кодом, і обмеження в
-- базі означало б міграцію на кожну нову формулу джерела при нульовому виграші — рядок сюди пише
-- лише класифікатор, і жодного іншого запису в цю колонку в системі немає.

ALTER TABLE message_classifications
  ADD COLUMN IF NOT EXISTS origin_zone text;

COMMENT ON COLUMN message_classifications.origin_zone IS
  'Зона поза Україною, з якої джерело повідомило походження загрози. NULL — джерело її не називало; '
  'це нормальний і найчастіший стан. Ніколи не виводиться з класу зброї: повідомлення про зліт '
  'авіації не називає аеродрому, і зона, здогадана за типом індикатора, була б припущенням системи, '
  'а не заявою джерела.';

-- Часткові індекси: рядків із зоною одиниці на тисячі, і обидва запити читають лише їх.
-- Перший — стрічка активності («які зони назвали за останні N хвилин»), другий — розбір по зоні.
CREATE INDEX IF NOT EXISTS message_classifications_origin_zone_recent_idx
  ON message_classifications (published_at DESC)
  WHERE origin_zone IS NOT NULL;

CREATE INDEX IF NOT EXISTS message_classifications_origin_zone_idx
  ON message_classifications (origin_zone, published_at DESC)
  WHERE origin_zone IS NOT NULL;
