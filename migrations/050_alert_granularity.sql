-- Що було виміряно
-- ================================================================================================
--
-- 19.08.2026, на бойовій базі та на живому ендпоінті дзеркала:
--
--   * за тиждень створено 212 обласних періодів тривоги, з них 32 по Харківщині, 27 по
--     Миколаївщині, 23 по Херсонщині — при тому, що жоден фід не показував ці області оголошеними
--     цілими: у них світилися окремі райони;
--   * джерелом цих періодів був відкат на агрегований фід дзеркала, який позначає область як
--     alertnow, коли світиться БУДЬ-ЯКА її частина. Відкат спрацьовував на 10 % опитувань
--     (94 з 917 за годину з чвертю), бо основний фід `?source=ual&raw` віддавав обрізане тіло;
--   * той самий основний фід оновлює свій кеш рівно раз на 121 с, тобто в середньому віддавав стан
--     хвилинної давності — найбільший доданок затримки сповіщення (p50 74 с проти 2.5 с через канал
--     ОВА).
--
-- Тому: (1) фідом деталізації став `skog` — та сама районна й громадна деталізація, що в `ual`
-- (у зрізі рівно 29 однакових районів під тривогою в обох), але кеш оновлюється раз на ~11 с;
-- (2) рівень області з фідів-згорток не читається взагалі; (3) оголошення рівня області приходить
-- окремим джерелом із фіда `klimenko`, який світить область лише тоді, коли її оголосили цілою.
--
-- Ця міграція додає лише те, що не можна виразити кодом: рядок другого джерела та псевдонім, без
-- якого назва Криму з нового фіда не розпізнається.

-- ------------------------------------------------------------------------------------------------
-- 1. Друге джерело того самого дзеркала: оголошення рівня області
-- ------------------------------------------------------------------------------------------------
--
-- Окремий рядок, а не другий фід усередині наявного джерела, бо знімок — це повне твердження одного
-- джерела про країну: `persistOfficialAlertSnapshot` гасить усе, чого в ньому немає. Два фіди в
-- одному знімку означали б, що збій одного гасить те, що тримає другий.
--
-- `independence_group` СПІЛЬНА з наявним дзеркалом (`community-alert-mirror`) і це навмисно: обидва
-- фіди — це той самий хост і той самий республікатор, тож вони не є двома незалежними
-- підтвердженнями й не мають ними прикидатися ніде, де рахується незалежність джерел.
INSERT INTO sources (id,name,source_type,tier,official,adapter_type,independence_group,public_url,enabled)
VALUES ('aerial-alerts-mirror-state','Повітряна тривога — дзеркало, оголошення області (ubilling)','api','A',true,
        'aerial_alerts_mirror','community-alert-mirror','https://ubilling.net.ua/aerialalerts/',true)
ON CONFLICT (id) DO NOTHING;

COMMENT ON TABLE sources IS
  'Джерела повідомлень і тривог. Два рядки дзеркала (aerial-alerts-mirror і -state) читають різні фіди одного хоста: перший — райони й громади, другий — оголошення рівня області.';

-- ------------------------------------------------------------------------------------------------
-- 2. Псевдонім «АР Крим»
-- ------------------------------------------------------------------------------------------------
--
-- Фід оголошень пише Крим саме так. Без цього рядка кожне опитування давало б нерозпізнану назву в
-- попередженні оператора — щохвилини, назавжди, про територію, де ця система нічого не оголошує.
UPDATE locations
   SET aliases = array(SELECT DISTINCT unnest(aliases || ARRAY['ар крим']))
 WHERE id = 'ua-43' AND NOT ('ар крим' = ANY(aliases));
