-- 051: громада стає рядком каталогу, а не аліасом свого району.
--
-- Чому. З міграції 050 детальний фід — `skog`, і він публікує громади: «Марганецька територіальна
-- громада», «Нікопольська територіальна громада», «Харківська територіальна громада». Каталог був
-- тритирівневим і згортав такі мітки в район через аліас, тож фід казав «громада», а система чула
-- «район». Людина в Харківській громаді й людина в селі за сорок кілометрів діставали однакове
-- «Харківський район», і одну з них попереджали не про те місце.
--
-- Ця міграція сама рядків не пише. Каталог наповнює імпортер KATOTTG
-- (`src/services/location-catalog.ts`), і робить це однією транзакцією: рядки громад зʼявляються
-- РАЗОМ зі зняттям їхніх аліасів із районів, тож стану, у якому одна й та сама назва належить двом
-- рядкам, не існує ні на мить. Тут — лише знімається відмітка «цю версію вже імпортовано», щоб
-- планувальник на найближчому старті перечитав довідник за новим планом.
--
-- Виміряно перед зміною, на бойовому каталозі й на справжньому довіднику 07.07.2026: 1772 рядки
-- громад, і при цьому 4240 написань до і 4240 після — назви громад УЖЕ лежали в каталозі, аліасами
-- районів. Тому розбір повідомлення став швидшим (0.061 → 0.036 мс): район більше не тягне за собою
-- до 3532 чужих написань. 135 назв повторюються; підказка областю з фіда розводить 104 з них, решта
-- 31 лишається відмовою — тією самою, якою була. Двома написаннями стало менше: у Джанкойському
-- районі дві Калінінські громади, і ні назва, ні область їх не розрізняють.
--
-- Що буде видно. Місто тепер висить під своєю громадою, а не під районом, — інакше тривога для
-- Харківської громади була б німою для підписників Харкова, які стоять до неї найближче.
-- Полігона в громади немає й не передбачається: `POLYGON_TIERS` лишає контури областям, районам і
-- містам-областям, а район під тривогою своєї громади дістає покриття `unmapped` — тобто світиться
-- як і раніше, бо детальнішого шару, який його підмінив би, на карті немає.
--
-- Одноразовий артефакт переходу: район, який світився ЛИШЕ через мітку громади, перестає бути
-- ствердженим сам по собі, тож його період закривається за звичайним дебаунсом. Підписник почує
-- спершу точнішу тривогу по громаді, а за хвилину — «відбій» по району. Це правда про район, а не
-- передчасний відбій: цілу його територію ніхто під тривогою не оголошував.

