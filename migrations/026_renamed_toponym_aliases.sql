  ('katottg-ua12100070010038698', 'katottg-ua12100000000039307', 'city', 'Самар',
   'UA12100070010038698', ARRAY['самар', 'новомосковськ'])
ON CONFLICT (id) DO UPDATE
  SET aliases = (SELECT array_agg(DISTINCT alias)
                   FROM unnest(locations.aliases || EXCLUDED.aliases) AS alias);
