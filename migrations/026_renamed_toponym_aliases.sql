-- ================================================================================================
-- 026 — старі назви перейменованих топонімів як алiаси
-- ================================================================================================
-- Декомунізаційна хвиля 2024 року перейменувала Красноградський район на Берестинський
-- (Красноград → Берестин) і Новомосковський на Самарівський (Новомосковськ → Самар). KATOTTG —
-- а отже й каталог — знає лише нові назви, але офіційний канал тривог досі пише старі:
-- за останні 48 годин застосунок зафіксував «Красноградський район» і «Новомосковський район»
-- як нерозвʼязні (журнальне попередження "provider locations could not be mapped", пʼять
-- входжень). Наслідок бойовий: тривога по цих районах не досягала карти.
--
-- Виправлення — алiаси старих назв на рядках із новими. Рядок каталогу один (жодного «другого
-- Красноградського району» на карті), стара назва — ще один спосіб його назвати. Відмінкові
-- форми — за зразком наявних алiасів цих рядків, бо канал пише «в Красноградський район»
-- (знахідний), а адміністрації — «Красноградського району» (родовий).
--
-- Форма INSERT … ON CONFLICT, а не UPDATE: у розгортанні ці рядки створює KATOTTG-синк, але у
-- свіжій базі (тестова, новий вузол до першого синку) їх ще немає, і голий UPDATE мовчки
-- нічого б не зробив — міграція виглядала б застосованою, а алiаси зʼявилися б лише після
-- першого синку. INSERT із повними даними рядка робить міграцію самодостатньою; при конфлікті
-- вона лише доливає алiаси (unnest || array_agg DISTINCT — ідемпотентно, як у 024), не
-- перезаписуючи того, що синк міг оновити.

INSERT INTO locations (id, parent_id, type, name_uk, official_code, aliases)
VALUES
  ('katottg-ua63060000000053698', 'ua-63', 'raion', 'Берестинський район', 'UA63060000000053698',
   ARRAY['берестинський', 'берестинський район', 'берестинського району', 'берестинському районі',
         'красноградський', 'красноградський район', 'красноградського району', 'красноградському районі']),
  ('katottg-ua12100000000039307', 'ua-12', 'raion', 'Самарівський район', 'UA12100000000039307',
   ARRAY['самарівський', 'самарівський район', 'самарівського району', 'самарівському районі',
         'новомосковський', 'новомосковський район', 'новомосковського району', 'новомосковському районі'])
ON CONFLICT (id) DO UPDATE
  SET aliases = (SELECT array_agg(DISTINCT alias)
                   FROM unnest(locations.aliases || EXCLUDED.aliases) AS alias);

